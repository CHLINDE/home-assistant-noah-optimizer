"""Dashboard template 25 restores the original Power Flow Card Plus visuals.

The v20 migration converted the default Power Flow Card Plus to the bundled
NOAH-specific card. The user prefers the original graphic with curved flows.
Restore only the recognizably generated v20 card; keep unrelated/custom cards,
including their layout and styling, untouched. This also upgrades already
stored v22/v23/v24 conditional wrappers without losing their offline display.
"""

from __future__ import annotations

from typing import Any

from . import dashboard_migration_v23 as _previous_migration  # noqa: F401
from . import dashboard_migration_v20 as _v20
from . import dashboard as _dashboard

# Must be greater than 24 so a locally tested early beta.3 dashboard migrates
# without deleting its stored state or recreating the entire dashboard.
_dashboard.DASHBOARD_TEMPLATE_VERSION = 25
_PATCH_MARKER = "_noah_template_v25_classic_flow_restored"


