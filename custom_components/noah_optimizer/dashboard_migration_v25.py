def _is_default_v20_card(
    card: dict[str, Any], replacements: dict[str, str], german: bool,
) -> bool:
    """Do not replace a custom flow card that has the same entity bindings."""
    return card == _v20._energy_flow_card(replacements, german=german)


def _is_default_wrapper(card: dict[str, Any]) -> bool:
    """Only inspect conditional stacks generated by our earlier migrations."""
    if card.get("type") != "vertical-stack":
        return False
    cards = card.get("cards")
    if not isinstance(cards, list) or len(cards) != 2:
        return False
    first, second = cards
    if not isinstance(first, dict) or not isinstance(second, dict):
        return False
    if first.get("type") != "conditional" or second.get("type") != "conditional":
        return False
    fallback = second.get("card")
    if not isinstance(fallback, dict) or fallback.get("type") not in {"markdown", "grid"}:
        return False
    live_conditions = first.get("conditions")
    if not isinstance(live_conditions, list) or len(live_conditions) != 1:
        return False
    return live_conditions[0].get("condition") == "state"


def _restore_classic_flow(
    config: dict[str, Any], replacements: dict[str, str], *, german: bool,
) -> bool:
    """Restore only default energy-flow cards, preserve all custom cards."""
    changed = False
    for view in config.get("views", []):
        if not isinstance(view, dict):
            continue
        for section in view.get("sections", []):
            if not isinstance(section, dict):
                continue
            cards = section.get("cards")
            if not isinstance(cards, list):
                continue
            for index, card in enumerate(cards):
                if not isinstance(card, dict):
                    continue

                if _is_default_v20_card(card, replacements, german):
                    cards[index] = _classic_power_flow(replacements, german=german)
                    changed = True
                elif _is_default_wrapper(card):
                    original = card["cards"][0].get("card")
                    if (
                        isinstance(original, dict)
                        and _is_default_v20_card(original, replacements, german)
                    ):
                        # Preserve the existing normal/offline conditional stack
                        # and change only its live graphical card.
                        card["cards"][0]["card"] = _classic_power_flow(
                            replacements, german=german,
                        )
                        changed = True
    return changed


def _install() -> None:
    if getattr(_dashboard, _PATCH_MARKER, False):
        return
    previous_migrate = _dashboard._migrate_dashboard_to_beta11
    previous_build = _dashboard._async_build_dashboard_config

    def migrate(hass, config, replacements):
        migrated, changed = previous_migrate(hass, config, replacements)
        german = (hass.config.language or "en").lower().startswith("de")
        restored = _restore_classic_flow(migrated, replacements, german=german)
        return migrated, changed or restored

    async def build(hass, entry):
        config = await previous_build(hass, entry)
        replacements = _dashboard._resolve_entities(hass, entry)
        german = (hass.config.language or "en").lower().startswith("de")
        _restore_classic_flow(config, replacements, german=german)
        return config

    _dashboard._migrate_dashboard_to_beta11 = migrate
    _dashboard._async_build_dashboard_config = build
    setattr(_dashboard, _PATCH_MARKER, True)


_install()
async_ensure_dashboard = _dashboard.async_ensure_dashboard
remove_dashboard_panel = _dashboard.remove_dashboard_panel
